#!/usr/bin/env python3
"""Generate Gateway/Paper/paper_gate_n32_data.h: a policy and its oracle
vectors, produced by the paper-experiments repo's
verified-combiner/test/gen_vectors.py. Default: the OPNsense 19.1.7 endpoint
policy (420 rules, n = 53); the first run used siemens-scalance-xb200 (254
rules, n = 32). The "n32" names are historical. Data only; the gate code is
the unchanged extracted GateLowGateDecide."""
import argparse, hashlib, subprocess
from pathlib import Path

ap = argparse.ArgumentParser()
ap.add_argument('--policy', default='opnsense-19.1.7')
policy = ap.parse_args().policy

root = Path(__file__).resolve().parents[2]
gen = Path('/home/iamfo470/phd/paper-experiments/verified-combiner/test/gen_vectors.py')
text = subprocess.check_output(['python3', str(gen), '--policy', policy], text=True)
lines = text.split('\n')
assert lines[0].startswith('P ')
n = int(lines[0].split()[1])
rules = [tuple(int(x) for x in l.split()) for l in lines[1:1 + 8 * n]]
qs = [tuple(int(x) for x in l.split()[1:]) for l in lines[1 + 8 * n:] if l.startswith('Q ')]
out = ['/* Generated by Gateway/tools/gen_gate_n32_data.py; do not edit. */',
       f'/* Source: {gen} --policy {policy}, sha256 {hashlib.sha256(text.encode()).hexdigest()} */',
       '#include <stdint.h>',
       f'#define GATE_N32_POLICY "{policy}"',
       f'#define GATE_N32_PARTITIONS {n}u',
       f'#define GATE_N32_VECTORS {len(qs)}u',
       'typedef struct { uint32_t path; uint8_t mask, min_role; uint16_t scope; } GateN32Rule;',
       'typedef struct { uint32_t path; uint8_t meth, role; uint16_t scope; uint8_t count, expected; } GateN32Vector;',
       'static const GateN32Rule gate_n32_rules[8u * GATE_N32_PARTITIONS] = {']
out += [f'  {{{p}u, {m}u, {o}u, {c}u}},' for p, m, o, c in rules]
out += ['};', 'static const GateN32Vector gate_n32_vectors[GATE_N32_VECTORS] = {']
out += [f'  {{{p}u, {m}u, {r}u, {s}u, {c}u, {e}u}},' for p, m, r, s, c, e in qs]
out += ['};']
(root / 'Gateway/Paper/paper_gate_n32_data.h').write_text('\n'.join(out) + '\n')
print(f'n={n} rules={len(rules)} vectors={len(qs)} accepts={sum(q[5] for q in qs)}')
